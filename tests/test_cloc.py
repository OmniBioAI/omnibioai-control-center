from __future__ import annotations

import re
import sys
from pathlib import Path


SCRIPTS_DIR = Path(__file__).resolve().parents[1] / "scripts"
if str(SCRIPTS_DIR) not in sys.path:
    sys.path.insert(0, str(SCRIPTS_DIR))

from sections.coverage import _coverage_cmd
from shared.cloc import (
    EXCLUDE_CONTENT,
    EXCLUDE_DIRS,
    NOT_MATCH_D,
    REPORT_EXCLUDE_DIRS,
)


def test_report_code_scan_excludes_generated_and_vendored_directories() -> None:
    excluded = set(EXCLUDE_DIRS.split(","))

    required = {
        "artifacts",
        "obsolete",
        "node_modules",
        "dist",
        "dist-packages",
        "build",
        "site-packages",
        "vendor",
        "coverage",
        "htmlcov",
        "playwright-report",
        "test-results",
        ".pytest_cache",
        ".mypy_cache",
        ".ruff_cache",
        ".workstreams",
        ".docusaurus",
    }
    assert required <= set(REPORT_EXCLUDE_DIRS)
    assert required <= excluded


def test_report_coverage_scan_uses_the_same_directory_exclusions() -> None:
    cmd = _coverage_cmd(["--cov=."])

    assert {f"--ignore={name}" for name in REPORT_EXCLUDE_DIRS} <= set(cmd)


def test_report_code_scan_matches_only_intended_directory_boundaries() -> None:
    excluded_paths = (
        "/repo/.venv-inventory/lib/python/site-packages",
        "/repo/dist-admin/assets/index.js",
        "/repo/results_workflow/output.txt",
        "/repo/ragbio.egg-info/PKG-INFO",
        "/repo/remediation/agent-a/repos/copied-repo/src/app.py",
    )
    source_paths = (
        "/repo/src/database/models.py",
        "/repo/plugins/data_manager/service.py",
        "/repo/src/cache_service/client.py",
        "/repo/src/results/component.tsx",
    )

    assert all(re.search(NOT_MATCH_D, path) for path in excluded_paths)
    assert not any(re.search(NOT_MATCH_D, path) for path in source_paths)


def test_report_code_scan_excludes_cython_output_without_hiding_all_c() -> None:
    assert re.search(EXCLUDE_CONTENT, "/* Generated by Cython 3.3.0 */")
    assert not re.search(EXCLUDE_CONTENT, "/* Hand-written C source */")
